//! LLM-powered semgrep rule synthesis (MoCQ paper: [arxiv:2504.16057](https://arxiv.org/abs/2504.16057))
//!
//! Generates semgrep YAML rules from CWE identifiers using LLM synthesis,
//! validates them via `semgrep --validate`, and persists valid rules.

